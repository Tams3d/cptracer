export function buildLlmsFullTxt(site?: URL): string {
  return [
    buildHomeMarkdown(site),
    "---",
    "",
    buildProfileMarkdown(site),
    "---",
    "",
    buildAboutMarkdown(site),
  ].join("\n");
}
