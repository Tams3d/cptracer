import { ABOUT_FAQS, ABOUT_PLATFORMS } from "@/lib/about-content";

function pageUrl(site: URL | undefined, path: string): string {
  return site ? new URL(path, site).href : path;
}

export function buildHomeMarkdown(site?: URL): string {
  return [
    "# cptracer",
    "",
    "> Local-first dashboard for Codeforces, AtCoder, and LeetCode profiles.",
    "",
    `Canonical page: ${pageUrl(site, "/")}`,
    "",
    "cptracer is a free, open-source web app that shows competitive programming",
    "statistics in one place. It reads public platform handles stored in your",
    "browser, then displays live ratings, ranks, solved counts, activity heatmaps,",
    "trend lines, and recent accepted problems. There is no account or database.",
    "",
    "## What it does",
    "",
    "- Shows current rating, rank, solved count, and profile link for each platform",
    "- Draws a daily activity heatmap for the current year",
    "- Draws a difficulty heatmap using official problem ratings where available",
    "- Plots daily accepted submissions for the total and each platform",
    "- Lists the latest accepted problems with tags and difficulty",
    "- Keeps handles and cached results in browser local storage",
    "",
    "## Supported platforms",
    "",
    "- Codeforces: profile statistics, submissions, and problem ratings",
    "- AtCoder: profile statistics, submissions, problem titles, and difficulty",
    "- LeetCode: profile statistics, submission calendar, and problem tags",
    "",
    "## Privacy",
    "",
    "Handles and cached statistics never leave the browser. Requests go directly",
    "from the browser to public platform APIs. Clearing site data removes every",
    "stored value.",
    "",
    "## Related pages",
    "",
    `- [Profile setup](${pageUrl(site, "/profile/")}): connect or edit handles.`,
    `- [About and FAQ](${pageUrl(site, "/about/")}): how the dashboard works.`,
    `- [llms.txt](${pageUrl(site, "/llms.txt")}): crawler and agent index.`,
    "",
  ].join("\n");
}

export function buildProfileMarkdown(site?: URL): string {
  return [
    "# Profile setup",
    "",
    "> Connect Codeforces, AtCoder, and LeetCode handles to cptracer.",
    "",
    `Canonical page: ${pageUrl(site, "/profile/")}`,
    "",
    "Enter a public handle for one or more platforms, then save. cptracer stores",
    "the handles in browser local storage and loads statistics for each connected",
    "platform. Handles can be edited or cleared at any time.",
    "",
    "## Fields",
    "",
    "- Codeforces handle: the username in a codeforces.com/profile URL",
    "- AtCoder handle: the username in an atcoder.jp/users URL",
    "- LeetCode handle: the username in a leetcode.com/u URL",
    "",
    "## Data handling",
    "",
    "No handle is sent to a cptracer server. The browser calls public platform",
    "APIs directly. Cached results are shown immediately and reused for five",
    "minutes, so page loads and route changes do not repeat a request. Press",
    "refresh to fetch new data at any time.",
    "",
    "## Related pages",
    "",
    `- [Dashboard](${pageUrl(site, "/")}): ratings, heatmaps, trends, recent solves.`,
    `- [About and FAQ](${pageUrl(site, "/about/")}): supported platforms and limits.`,
    `- [llms.txt](${pageUrl(site, "/llms.txt")}): crawler and agent index.`,
    "",
  ].join("\n");
}

export function buildAboutMarkdown(site?: URL): string {
  return [
    "# About cptracer",
    "",
    "> A local-first dashboard for competitive programming profiles.",
    "",
    `Canonical page: ${pageUrl(site, "/about/")}`,
    "",
    "cptracer brings Codeforces, AtCoder, and LeetCode statistics into one clean",
    "dashboard. It is open source under the MIT licence and runs without an",
    "account, database, or analytics service.",
    "",
    "## How it works",
    "",
    "The browser reads handles from local storage and renders saved results",
    "immediately. A result younger than five minutes is reused without a network",
    "request; older results are refreshed in the background. Press refresh to",
    "fetch new data at any time.",
    "",
    "## Supported platforms",
    "",
    ...ABOUT_PLATFORMS.map(
      (platform) => `- ${platform.name}: ${platform.summary}`,
    ),
    "",
    "CodeChef and CSES are not supported because their public interfaces are",
    "unreliable for browser requests.",
    "",
    "## Frequently asked questions",
    "",
    ...ABOUT_FAQS.flatMap((faq) => [`### ${faq.question}`, "", faq.answer, ""]),
    "## Related pages",
    "",
    `- [Dashboard](${pageUrl(site, "/")}): live statistics and activity.`,
    `- [Profile setup](${pageUrl(site, "/profile/")}): connect handles.`,
    `- [llms.txt](${pageUrl(site, "/llms.txt")}): crawler and agent index.`,
    "",
  ].join("\n");
}

